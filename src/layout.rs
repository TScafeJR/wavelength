//! Layout: block flow, inline content in line boxes, inline-blocks, form
//! controls, images and a simplified table algorithm.
//!
//! Block boxes stack vertically and adjacent sibling margins collapse. Inline
//! content is broken into lines at spaces. Tables size their columns from
//! their content and any widths given. Floats, positioning, flexbox, grid and
//! margin collapsing between parents and children are not implemented yet;
//! see the roadmap.

use std::collections::HashMap;

use crate::dom::{Document, NodeData, NodeId};
use crate::font::{Face, Fonts};
use crate::style::{
    AlignItems, Color, Display, Edges, Justify, Style, TextAlign, TextTransform, VerticalAlign,
};

/// A width no real container has, used to measure content without wrapping it.
const UNBOUNDED: f32 = 1.0e6;
/// Slack when deciding whether a word still fits, to absorb rounding in summed widths.
const FIT_TOLERANCE: f32 = 0.01;
/// The gap browsers leave between table cells unless told otherwise.
const DEFAULT_CELL_SPACING: f32 = 2.0;
const PLACEHOLDER_COLOR: Color = Color::rgb(117, 117, 117);

/// A rectangle in CSS pixels, relative to the top left of the page.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Rect {
    /// The left edge.
    pub x: f32,
    /// The top edge.
    pub y: f32,
    /// The width.
    pub width: f32,
    /// The height.
    pub height: f32,
}

impl Rect {
    /// Whether the point lies inside the rectangle.
    pub fn contains(&self, x: f32, y: f32) -> bool {
        x >= self.x && x < self.x + self.width && y >= self.y && y < self.y + self.height
    }
}

/// A run of text placed on one line.
#[derive(Debug, Clone, PartialEq)]
pub struct Fragment {
    /// The text node the run comes from, or the form control that displays it.
    pub node: NodeId,
    /// The area the run occupies, from the font's ascent to its descent.
    pub rect: Rect,
    /// The y coordinate of the baseline.
    pub baseline: f32,
    /// The characters to draw.
    pub text: String,
    /// The font size in pixels.
    pub size: f32,
    /// The font face used.
    pub face: Face,
    /// The text colour.
    pub color: Color,
    /// Whether the run is underlined.
    pub underline: bool,
}

/// A laid-out box, the boxes inside it and the text it places directly.
#[derive(Debug, Clone)]
pub struct LayoutBox {
    /// The element that generated this box.
    pub node: NodeId,
    /// The border box: content, padding and border, without margins.
    pub rect: Rect,
    /// The element's computed style.
    pub style: Style,
    /// Child boxes in document order.
    pub children: Vec<LayoutBox>,
    /// Text placed in this box's own lines.
    pub fragments: Vec<Fragment>,
    /// The width this box would like including margins, used to size shrink-to-fit parents.
    preferred_width: f32,
}

impl LayoutBox {
    /// Finds the box generated by `node` in this subtree.
    pub fn find(&self, node: NodeId) -> Option<&LayoutBox> {
        if self.node == node {
            return Some(self);
        }
        self.children.iter().find_map(|child| child.find(node))
    }

    /// The node drawn at a point: the topmost box or text run that contains it.
    pub fn hit_test(&self, x: f32, y: f32) -> Option<NodeId> {
        // Children may overflow their parent, so they are searched regardless of this box's bounds.
        if let Some(node) = self.children.iter().rev().find_map(|c| c.hit_test(x, y)) {
            return Some(node);
        }
        if let Some(fragment) = self.fragments.iter().find(|f| f.rect.contains(x, y)) {
            return Some(fragment.node);
        }
        self.rect.contains(x, y).then_some(self.node)
    }

    fn translate(&mut self, dx: f32, dy: f32) {
        self.rect.x += dx;
        self.rect.y += dy;
        self.translate_contents(dx, dy);
    }

    fn translate_contents(&mut self, dx: f32, dy: f32) {
        for fragment in &mut self.fragments {
            fragment.rect.x += dx;
            fragment.rect.y += dy;
            fragment.baseline += dy;
        }
        for child in &mut self.children {
            child.translate(dx, dy);
        }
    }
}

/// Everything layout needs to know about a document.
#[derive(Debug, Clone, Copy)]
pub struct Context<'a> {
    /// The document tree.
    pub doc: &'a Document,
    /// One computed style per node, indexed by node id.
    pub styles: &'a [Style],
    /// The fonts used to measure text.
    pub fonts: &'a Fonts,
    /// The pixel size of each image that was loaded, by `img` element.
    pub image_sizes: &'a HashMap<NodeId, (u32, u32)>,
    /// Text typed into form fields, which overrides their `value` attribute.
    pub values: &'a HashMap<NodeId, String>,
    /// The form field that has keyboard focus, which is drawn with a caret.
    pub focused: Option<NodeId>,
}

/// Lays out the document for a viewport of the given width.
///
/// Returns `None` when the root element generates no box.
pub fn layout(context: Context<'_>, viewport_width: f32) -> Option<LayoutBox> {
    let root = context.doc.find_element("html")?;
    let style = &context.styles[root.0];
    (style.display != Display::None).then(|| {
        let top = style.margin.top.unwrap_or(0.0);
        context.flow_box(root, viewport_width, 0.0, top, false)
    })
}

fn margins(style: &Style) -> Edges<f32> {
    Edges {
        top: style.margin.top.unwrap_or(0.0),
        right: style.margin.right.unwrap_or(0.0),
        bottom: style.margin.bottom.unwrap_or(0.0),
        left: style.margin.left.unwrap_or(0.0),
    }
}

/// The horizontal space a box's border and padding take up.
fn frame_width(style: &Style) -> f32 {
    let border = style.border();
    border.left + style.padding.left + style.padding.right + border.right
}

fn frame_height(style: &Style) -> f32 {
    let border = style.border();
    border.top + style.padding.top + style.padding.bottom + border.bottom
}

/// The margin between two boxes whose margins touch.
fn collapse(first: f32, second: f32) -> f32 {
    if first >= 0.0 && second >= 0.0 {
        first.max(second)
    } else if first < 0.0 && second < 0.0 {
        first.min(second)
    } else {
        first + second
    }
}

impl<'a> Context<'a> {
    fn style(&self, node: NodeId) -> &'a Style {
        &self.styles[node.0]
    }

    /// Lays out a block-level box whose border box starts at `y`, inside a
    /// containing block that starts at `x` and is `containing_width` wide.
    fn flow_box(
        &self,
        node: NodeId,
        containing_width: f32,
        x: f32,
        y: f32,
        measuring: bool,
    ) -> LayoutBox {
        if self.style(node).display == Display::Table {
            self.table(node, containing_width, x, y, measuring)
        } else if self.style(node).display == Display::Flex {
            self.flex(node, containing_width, x, y, None, measuring)
        } else if self.is_replaced(node) {
            // An image or form control displayed as a block keeps its own size.
            let mut replaced = self.atomic(node, containing_width, measuring);
            let left = self.margin_left(node, containing_width, replaced.rect.width);
            replaced.translate(x + left, y);
            replaced
        } else {
            self.block(node, containing_width, x, y, None, measuring)
        }
    }

    /// Whether the element's content comes from outside the document tree, so it is sized as a unit.
    fn is_replaced(&self, node: NodeId) -> bool {
        let name = self
            .doc
            .element(node)
            .map_or("", |element| element.name.as_str());
        matches!(name, "img" | "input" | "textarea" | "select")
    }

    /// The content width a style asks for, or `None` when it is `auto`.
    fn specified_width(
        &self,
        style: &Style,
        containing_width: f32,
        measuring: bool,
    ) -> Option<f32> {
        // A percentage of an unknown width cannot be resolved while measuring.
        let length = style
            .width
            .filter(|length| length.is_fixed() || !measuring)?;
        let outer = length.resolve(containing_width);
        Some(if style.border_box {
            (outer - frame_width(style)).max(0.0)
        } else {
            outer
        })
    }

    /// The content height a style asks for, when that is a fixed length.
    fn specified_height(&self, style: &Style) -> Option<f32> {
        let height = style.height.filter(|length| length.is_fixed())?.px;
        Some(if style.border_box {
            (height - frame_height(style)).max(0.0)
        } else {
            height
        })
    }

    /// Applies `max-width` and then `min-width` to a content width.
    fn clamp_width(
        &self,
        style: &Style,
        width: f32,
        containing_width: f32,
        measuring: bool,
    ) -> f32 {
        let inside = |outer: f32| {
            if style.border_box {
                (outer - frame_width(style)).max(0.0)
            } else {
                outer
            }
        };
        let limit = style
            .max_width
            .filter(|length| length.is_fixed() || !measuring);
        let capped = limit.map_or(width, |length| {
            width.min(inside(length.resolve(containing_width)))
        });
        capped.max(inside(style.min_width))
    }

    /// Applies `max-height` and then `min-height` to a content height.
    fn clamp_height(&self, style: &Style, height: f32) -> f32 {
        let inside = |outer: f32| {
            if style.border_box {
                (outer - frame_height(style)).max(0.0)
            } else {
                outer
            }
        };
        let capped = style
            .max_height
            .map_or(height, |limit| height.min(inside(limit)));
        capped.max(inside(style.min_height))
    }

    /// Where a box of the given border-box width sits horizontally in its containing block.
    fn margin_left(&self, node: NodeId, containing_width: f32, border_box_width: f32) -> f32 {
        let style = self.style(node);
        let free =
            |fixed_margins: f32| (containing_width - border_box_width - fixed_margins).max(0.0);
        let parent_centers = self
            .doc
            .node(node)
            .parent
            .is_some_and(|parent| self.style(parent).center_blocks);
        match (style.margin.left, style.margin.right) {
            (Some(left), Some(right)) if parent_centers => left + free(left + right) / 2.0,
            (Some(left), _) => left,
            // Auto margins absorb the free space, and count as zero when there is none.
            (None, Some(right)) => free(right),
            (None, None) => free(0.0) / 2.0,
        }
    }

    /// Lays out a block container. `forced_width` fixes the content width, for
    /// boxes whose width was decided by their parent.
    fn block(
        &self,
        node: NodeId,
        containing_width: f32,
        x: f32,
        y: f32,
        forced_width: Option<f32>,
        measuring: bool,
    ) -> LayoutBox {
        let style = *self.style(node);
        let (border, padding, margin) = (style.border(), style.padding, margins(&style));
        let frame = frame_width(&style);

        let specified = forced_width.or(self.specified_width(&style, containing_width, measuring));
        let fill = (containing_width - margin.left - margin.right - frame).max(0.0);
        let width = match forced_width {
            Some(forced) => forced,
            None => self.clamp_width(
                &style,
                specified.unwrap_or(fill),
                containing_width,
                measuring,
            ),
        };

        let rect_x = x + self.margin_left(node, containing_width, width + frame);
        let content_x = rect_x + border.left + padding.left;
        let content_y = y + border.top + padding.top;

        let mut flow = Flow::new(self, node, content_x, width, content_y, measuring);
        self.walk(&mut flow, node);
        let (children, mut fragments, content_bottom, extent) = flow.finish();
        fragments.extend(self.list_marker(node, &style, content_x, content_y));

        let natural_height = content_bottom - content_y;
        let content_height = self.clamp_height(
            &style,
            self.specified_height(&style).unwrap_or(natural_height),
        );
        let has_fixed_width = specified.is_some() || width < fill;
        let preferred_content = if has_fixed_width { width } else { extent };
        LayoutBox {
            node,
            rect: Rect {
                x: rect_x,
                y,
                width: width + frame,
                height: content_height + frame_height(&style),
            },
            style,
            children,
            fragments,
            preferred_width: preferred_content + frame + margin.left + margin.right,
        }
    }

    /// Feeds the children of `parent` into a flow, descending through inline elements.
    fn walk(&self, flow: &mut Flow<'_, 'a>, parent: NodeId) {
        for &child in &self.doc.node(parent).children {
            self.walk_child(flow, parent, child);
        }
    }

    /// Feeds one child of `parent` into a flow.
    fn walk_child(&self, flow: &mut Flow<'_, 'a>, parent: NodeId, child: NodeId) {
        let style = self.style(child);
        match &self.doc.node(child).data {
            NodeData::Document => {}
            NodeData::Text(text) => flow.text(child, text, style),
            // Absolutely positioned boxes are left out until positioning is implemented.
            NodeData::Element(_) if style.display == Display::None || style.out_of_flow => {}
            NodeData::Element(element) if element.name == "br" => flow.line_break(style),
            NodeData::Element(_) => match style.display {
                Display::None => {}
                Display::Inline if !self.is_replaced(child) => self.walk(flow, child),
                Display::Inline | Display::InlineBlock => {
                    let inline_box = self.atomic(child, flow.width, flow.measuring);
                    flow.atomic(inline_box, margins(style), self.style(parent).nowrap);
                }
                Display::Block
                | Display::Flex
                | Display::Table
                | Display::TableRow
                | Display::TableCell => {
                    flow.block_child(child);
                }
            },
        }
    }

    /// The bullet or number drawn beside a list item, to the left of its first line.
    fn list_marker(
        &self,
        node: NodeId,
        style: &Style,
        content_x: f32,
        content_y: f32,
    ) -> Option<Fragment> {
        if !(style.list_item && style.list_marker) {
            return None;
        }
        let parent = self.doc.node(node).parent?;
        let ordered = self
            .doc
            .element(parent)
            .is_some_and(|list| list.name == "ol");
        let text = if ordered {
            let items = self.doc.node(parent).children.iter();
            let is_item =
                |&&child: &&NodeId| self.doc.element(child).is_some_and(|e| e.name == "li");
            let index = items.filter(is_item).position(|&child| child == node)?;
            let start = self
                .doc
                .element(parent)?
                .attribute("start")
                .and_then(|start| start.parse::<usize>().ok());
            format!("{}.", start.unwrap_or(1) + index)
        } else {
            "\u{2022}".to_owned()
        };
        let (size, face) = (style.font_size, style.face());
        let metrics = self.fonts.metrics(size, face);
        let width = self.fonts.measure(&text, size, face);
        let baseline = content_y + text_extent(self.fonts, style).0;
        Some(Fragment {
            node,
            rect: Rect {
                x: content_x - width - size * 0.4,
                y: baseline - metrics.ascent,
                width,
                height: metrics.ascent + metrics.descent,
            },
            baseline,
            text,
            size,
            face,
            color: style.text_color(),
            underline: false,
        })
    }

    /// Lays out a box that sits on a line as one unit, with its border box at the origin.
    fn atomic(&self, node: NodeId, available: f32, measuring: bool) -> LayoutBox {
        let style = *self.style(node);
        let name = self
            .doc
            .element(node)
            .map_or("", |element| element.name.as_str());
        let mut laid_out = match name {
            "img" => {
                let (width, height) = self.image_size(node, &style);
                self.leaf(node, style, width, height, Vec::new())
            }
            "input" => self.input(node, style),
            "textarea" | "select" => {
                let columns = if name == "textarea" { 20.0 } else { 8.0 };
                let rows = if name == "textarea" { 2.0 } else { 1.0 };
                let metrics = self.fonts.metrics(style.font_size, style.face());
                let line =
                    style.used_line_height(metrics.ascent + metrics.descent + metrics.line_gap);
                let width = self.fonts.measure("0", style.font_size, style.face()) * columns;
                self.leaf(
                    node,
                    style,
                    self.fixed_width(&style).unwrap_or(width),
                    line * rows,
                    Vec::new(),
                )
            }
            _ => {
                let margin = margins(&style);
                let outside = frame_width(&style) + margin.left + margin.right;
                let width = match self.specified_width(&style, available, measuring) {
                    Some(width) => width,
                    None => {
                        // Shrink to fit: as wide as the content wants, up to the space available.
                        let probe = self.block(node, UNBOUNDED, 0.0, 0.0, None, true);
                        let preferred = (probe.preferred_width - outside).max(0.0);
                        preferred.min((available - outside).max(0.0))
                    }
                };
                let width = self.clamp_width(&style, width, available, measuring);
                self.block(node, available, 0.0, 0.0, Some(width), measuring)
            }
        };
        let (dx, dy) = (-laid_out.rect.x, -laid_out.rect.y);
        laid_out.translate(dx, dy);
        laid_out
    }

    fn fixed_width(&self, style: &Style) -> Option<f32> {
        self.specified_width(style, 0.0, true)
    }

    /// A box with a known content size and no flowed children.
    fn leaf(
        &self,
        node: NodeId,
        style: Style,
        width: f32,
        height: f32,
        fragments: Vec<Fragment>,
    ) -> LayoutBox {
        let margin = margins(&style);
        let rect = Rect {
            x: 0.0,
            y: 0.0,
            width: width + frame_width(&style),
            height: height + frame_height(&style),
        };
        LayoutBox {
            node,
            rect,
            style,
            children: Vec::new(),
            fragments,
            preferred_width: rect.width + margin.left + margin.right,
        }
    }

    /// The content size of an image: what CSS or the markup asks for, else the picture's own size.
    fn image_size(&self, node: NodeId, style: &Style) -> (f32, f32) {
        let pixels =
            |length: Option<crate::style::Length>| length.filter(|l| l.is_fixed()).map(|l| l.px);
        let intrinsic = self
            .image_sizes
            .get(&node)
            .map(|&(w, h)| (w as f32, h as f32));
        match (pixels(style.width), pixels(style.height), intrinsic) {
            (Some(width), Some(height), _) => (width, height),
            (Some(width), None, Some((iw, ih))) if iw > 0.0 => (width, width * ih / iw),
            (None, Some(height), Some((iw, ih))) if ih > 0.0 => (height * iw / ih, height),
            (None, None, Some(size)) => size,
            (width, height, _) => (width.unwrap_or(0.0), height.unwrap_or(0.0)),
        }
    }

    /// A form field or button, with its value or label as text inside.
    fn input(&self, node: NodeId, style: Style) -> LayoutBox {
        let Some(element) = self.doc.element(node) else {
            return self.leaf(node, style, 0.0, 0.0, Vec::new());
        };
        let kind = element
            .attribute("type")
            .unwrap_or("text")
            .to_ascii_lowercase();
        if matches!(kind.as_str(), "checkbox" | "radio") {
            return self.leaf(node, style, 11.0, 11.0, Vec::new());
        }
        let is_button = matches!(kind.as_str(), "submit" | "button" | "reset");
        let (size, bold) = (style.font_size, style.face());
        let metrics = self.fonts.metrics(size, bold);
        let line = style.used_line_height(metrics.ascent + metrics.descent + metrics.line_gap);

        let typed = self.values.get(&node).map(String::as_str);
        let value = typed.or(element.attribute("value")).unwrap_or_default();
        let (mut text, mut color) = (value.to_owned(), style.text_color());
        if is_button && text.is_empty() {
            text = match kind.as_str() {
                "submit" => "Submit".to_owned(),
                "reset" => "Reset".to_owned(),
                _ => String::new(),
            };
        } else if kind == "password" {
            text = "\u{2022}".repeat(value.chars().count());
        }
        if self.focused == Some(node) {
            text.push('|');
        } else if text.is_empty() && !is_button {
            text = element
                .attribute("placeholder")
                .unwrap_or_default()
                .to_owned();
            color = style.fade(PLACEHOLDER_COLOR);
        }

        let text_width = self.fonts.measure(&text, size, bold);
        let columns = element
            .attribute("size")
            .and_then(|size| size.parse::<f32>().ok())
            .filter(|columns| *columns > 0.0)
            .unwrap_or(20.0);
        let natural_width = if is_button {
            text_width
        } else {
            self.fonts.measure("0", size, bold) * columns
        };
        let width = self.fixed_width(&style).unwrap_or(natural_width);
        let height = self.specified_height(&style).unwrap_or(line);

        let border = style.border();
        let inset = match style.text_align {
            TextAlign::Center => ((width - text_width) / 2.0).max(0.0),
            _ => 0.0,
        };
        let top =
            border.top + style.padding.top + (height - metrics.ascent - metrics.descent) / 2.0;
        let fragment = Fragment {
            node,
            rect: Rect {
                x: border.left + style.padding.left + inset,
                y: top,
                width: text_width,
                height: metrics.ascent + metrics.descent,
            },
            baseline: top + metrics.ascent,
            text,
            size,
            face: bold,
            color,
            underline: false,
        };
        let fragments = if fragment.text.is_empty() {
            Vec::new()
        } else {
            vec![fragment]
        };
        self.leaf(node, style, width, height, fragments)
    }

    /// Lays out a table: columns are sized from their cells, then rows are stacked.
    fn table(
        &self,
        node: NodeId,
        containing_width: f32,
        x: f32,
        y: f32,
        measuring: bool,
    ) -> LayoutBox {
        let style = *self.style(node);
        let (border, padding, margin) = (style.border(), style.padding, margins(&style));
        let frame = frame_width(&style);
        let spacing = self
            .doc
            .element(node)
            .and_then(|table| table.attribute("cellspacing")?.parse::<f32>().ok())
            .filter(|spacing| *spacing >= 0.0)
            .unwrap_or(DEFAULT_CELL_SPACING);

        // Rows are direct children or sit one level down, inside a row group such as `tbody`.
        let displayed = |parent: NodeId, display: Display| {
            let children = self.doc.node(parent).children.iter().copied();
            children.filter(move |&child| {
                self.doc.element(child).is_some() && self.style(child).display == display
            })
        };
        let mut rows: Vec<NodeId> = Vec::new();
        for &child in &self.doc.node(node).children {
            match self.style(child).display {
                Display::TableRow if self.doc.element(child).is_some() => rows.push(child),
                Display::Block => rows.extend(displayed(child, Display::TableRow)),
                _ => {}
            }
        }
        let cells: Vec<Vec<NodeId>> = rows
            .iter()
            .map(|&row| displayed(row, Display::TableCell).collect())
            .collect();
        let column_count = cells.iter().map(Vec::len).max().unwrap_or(0);

        // What each column needs: its widest content, and the largest width any cell asks for.
        let mut content = vec![0.0f32; column_count];
        let mut percent = vec![0.0f32; column_count];
        for row in &cells {
            for (column, &cell) in row.iter().enumerate() {
                let cell_style = self.style(cell);
                let probe = self.block(cell, UNBOUNDED, 0.0, 0.0, None, true);
                content[column] = content[column].max(probe.preferred_width);
                match cell_style.width {
                    Some(length) if length.is_fixed() => {
                        content[column] = content[column].max(length.px + frame_width(cell_style));
                    }
                    Some(length) => percent[column] = percent[column].max(length.percent / 100.0),
                    None => {}
                }
            }
        }

        let gaps = spacing * (column_count as f32 + 1.0);
        let available = (containing_width - margin.left - margin.right - frame).max(0.0);
        let percent_total = percent.iter().sum::<f32>().min(0.95);
        let flexible: f32 = (0..column_count)
            .filter(|&c| percent[c] == 0.0)
            .map(|c| content[c])
            .sum();
        // The narrowest table in which every percentage column still fits its content.
        let mut natural = flexible / (1.0 - percent_total);
        for column in 0..column_count {
            if percent[column] > 0.0 {
                natural = natural.max(content[column] / percent[column]);
            }
        }
        let natural = natural + gaps;
        let width = match style.width {
            Some(length) if length.is_fixed() => length.px.max(gaps),
            Some(length) if !measuring => length.resolve(available).max(gaps),
            _ if measuring => natural,
            _ => natural.min(available),
        };

        let inner = (width - gaps).max(0.0);
        let percent_width: f32 = percent.iter().map(|share| share * inner).sum();
        let remaining = (inner - percent_width).max(0.0);
        let flexible_count = percent.iter().filter(|share| **share == 0.0).count().max(1) as f32;
        let column_widths: Vec<f32> = (0..column_count)
            .map(|column| {
                if percent[column] > 0.0 {
                    percent[column] * inner
                } else if flexible > 0.0 {
                    remaining * content[column] / flexible
                } else {
                    remaining / flexible_count
                }
            })
            .collect();

        let rect_x = x + self.margin_left(node, containing_width, width + frame);
        let content_x = rect_x + border.left + padding.left;
        let content_y = y + border.top + padding.top;
        let mut children = Vec::with_capacity(rows.len());
        let mut cursor_y = content_y + spacing;
        for (&row, row_cells) in rows.iter().zip(&cells) {
            let mut cell_boxes = Vec::with_capacity(row_cells.len());
            let mut cursor_x = content_x + spacing;
            for (column, &cell) in row_cells.iter().enumerate() {
                let column_width = column_widths[column];
                let cell_width = (column_width - frame_width(self.style(cell))).max(0.0);
                let mut cell_box = self.block(
                    cell,
                    column_width,
                    cursor_x,
                    cursor_y,
                    Some(cell_width),
                    measuring,
                );
                cell_box.translate(cursor_x - cell_box.rect.x, 0.0);
                cell_boxes.push(cell_box);
                cursor_x += column_width + spacing;
            }
            let row_style = *self.style(row);
            let specified_height = self.specified_height(&row_style).unwrap_or(0.0);
            let row_height = cell_boxes
                .iter()
                .map(|c| c.rect.height)
                .fold(specified_height, f32::max);
            for cell_box in &mut cell_boxes {
                let extra = row_height - cell_box.rect.height;
                let shift = match cell_box.style.vertical_align {
                    VerticalAlign::Middle => extra / 2.0,
                    VerticalAlign::Bottom => extra,
                    VerticalAlign::Top | VerticalAlign::Baseline => 0.0,
                };
                cell_box.translate_contents(0.0, shift);
                cell_box.rect.height = row_height;
            }
            children.push(LayoutBox {
                node: row,
                rect: Rect {
                    x: content_x,
                    y: cursor_y,
                    width,
                    height: row_height,
                },
                style: row_style,
                children: cell_boxes,
                fragments: Vec::new(),
                preferred_width: width,
            });
            cursor_y += row_height + spacing;
        }

        let rows_height = if rows.is_empty() {
            0.0
        } else {
            cursor_y - content_y
        };
        let content_height = self
            .specified_height(&style)
            .map_or(rows_height, |height| height.max(rows_height));
        LayoutBox {
            node,
            rect: Rect {
                x: rect_x,
                y,
                width: width + frame,
                height: content_height + frame_height(&style),
            },
            style,
            children,
            fragments: Vec::new(),
            preferred_width: width + frame + margin.left + margin.right,
        }
    }
}

/// A child of a flex container.
enum FlexItem {
    /// An element, which becomes an item whatever its own `display` says.
    Element(NodeId),
    /// A run of text placed directly in the container, wrapped in a box of its own.
    Anonymous(Vec<NodeId>),
}

/// What is known about a flex item before its final size is decided.
struct FlexMeasure {
    /// The content width the item starts from.
    base: f32,
    /// Its border, padding and fixed horizontal margins.
    outside: f32,
    /// The margins as specified, where `None` is `auto`.
    margin: Edges<Option<f32>>,
    grow: f32,
    /// Whether the item's height is `auto`, so `align-items: stretch` may change it.
    stretches: bool,
}

impl<'a> Context<'a> {
    /// The items of a flex container, in order.
    fn flex_items(&self, node: NodeId) -> Vec<FlexItem> {
        let mut items = Vec::new();
        let mut text_run: Vec<NodeId> = Vec::new();
        for &child in &self.doc.node(node).children {
            match &self.doc.node(child).data {
                NodeData::Text(text) if !text.trim().is_empty() => text_run.push(child),
                NodeData::Element(_) => {
                    let style = self.style(child);
                    if style.display == Display::None || style.out_of_flow {
                        continue;
                    }
                    if !text_run.is_empty() {
                        items.push(FlexItem::Anonymous(std::mem::take(&mut text_run)));
                    }
                    items.push(FlexItem::Element(child));
                }
                _ => {}
            }
        }
        if !text_run.is_empty() {
            items.push(FlexItem::Anonymous(text_run));
        }
        items
    }

    /// Lays out one flex item with its border box at the origin. With a
    /// `width` the item's content is exactly that wide; without one the item
    /// is measured at the width its content would like.
    fn flex_item(
        &self,
        parent: NodeId,
        item: &FlexItem,
        width: Option<f32>,
        measuring: bool,
    ) -> LayoutBox {
        let measuring = measuring || width.is_none();
        let mut laid_out = match item {
            FlexItem::Anonymous(nodes) => {
                let mut flow = Flow::new(
                    self,
                    parent,
                    0.0,
                    width.unwrap_or(UNBOUNDED),
                    0.0,
                    measuring,
                );
                for &node in nodes {
                    self.walk_child(&mut flow, parent, node);
                }
                let (children, fragments, bottom, extent) = flow.finish();
                LayoutBox {
                    node: parent,
                    rect: Rect {
                        x: 0.0,
                        y: 0.0,
                        width: width.unwrap_or(extent),
                        height: bottom,
                    },
                    style: self.style(parent).anonymous(),
                    children,
                    fragments,
                    preferred_width: extent,
                }
            }
            FlexItem::Element(node) => {
                let style = self.style(*node);
                let margin = margins(style);
                let containing = match width {
                    Some(width) => width + frame_width(style) + margin.left + margin.right,
                    None => UNBOUNDED,
                };
                match style.display {
                    Display::Table => self.table(*node, containing, 0.0, 0.0, measuring),
                    Display::Flex => self.flex(*node, containing, 0.0, 0.0, width, measuring),
                    _ if self.is_replaced(*node) => self.atomic(*node, containing, measuring),
                    _ => self.block(*node, containing, 0.0, 0.0, width, measuring),
                }
            }
        };
        let (dx, dy) = (-laid_out.rect.x, -laid_out.rect.y);
        laid_out.translate(dx, dy);
        laid_out
    }

    /// Works out where each flex item starts from: its base size, margins and grow factor.
    fn flex_measure(
        &self,
        parent: NodeId,
        item: &FlexItem,
        container_width: f32,
        measuring: bool,
    ) -> FlexMeasure {
        let FlexItem::Element(node) = item else {
            let probe = self.flex_item(parent, item, None, measuring);
            return FlexMeasure {
                base: probe.preferred_width,
                outside: 0.0,
                margin: Edges::all(Some(0.0)),
                grow: 0.0,
                stretches: true,
            };
        };
        let style = self.style(*node);
        let fixed = margins(style);
        let outside = frame_width(style) + fixed.left + fixed.right;
        let base = match self.specified_width(style, container_width, measuring) {
            Some(width) => width,
            // An item with a zero basis is sized by its grow factor alone, once there is space to share.
            // In a column the basis is a height, so it says nothing about the item's width.
            None if style.flex_basis_zero && !measuring && !self.style(parent).flex_column => 0.0,
            None => (self
                .flex_item(parent, item, None, measuring)
                .preferred_width
                - outside)
                .max(0.0),
        };
        FlexMeasure {
            base: self.clamp_width(style, base, container_width, measuring),
            outside,
            margin: style.margin,
            grow: style.flex_grow,
            stretches: style.height.is_none() && !self.is_replaced(*node),
        }
    }

    /// Lays out a flex container. `forced_width` fixes the content width, for
    /// containers that are themselves flex items.
    fn flex(
        &self,
        node: NodeId,
        containing_width: f32,
        x: f32,
        y: f32,
        forced_width: Option<f32>,
        measuring: bool,
    ) -> LayoutBox {
        let style = *self.style(node);
        let (border, padding, margin) = (style.border(), style.padding, margins(&style));
        let frame = frame_width(&style);
        let specified = forced_width.or(self.specified_width(&style, containing_width, measuring));
        let fill = (containing_width - margin.left - margin.right - frame).max(0.0);
        let width = match forced_width {
            Some(forced) => forced,
            None => self.clamp_width(
                &style,
                specified.unwrap_or(fill),
                containing_width,
                measuring,
            ),
        };
        let rect_x = x + self.margin_left(node, containing_width, width + frame);
        let content_x = rect_x + border.left + padding.left;
        let content_y = y + border.top + padding.top;
        let fixed_height = self.specified_height(&style);

        let items = self.flex_items(node);
        let measures: Vec<FlexMeasure> = items
            .iter()
            .map(|item| self.flex_measure(node, item, width, measuring))
            .collect();
        let (mut children, natural_height, extent) = if style.flex_column {
            self.flex_column(
                node,
                &style,
                &items,
                &measures,
                width,
                fixed_height,
                measuring,
            )
        } else {
            self.flex_rows(
                node,
                &style,
                &items,
                &measures,
                width,
                fixed_height,
                measuring,
            )
        };
        for child in &mut children {
            child.translate(content_x, content_y);
        }

        let content_height = self.clamp_height(&style, fixed_height.unwrap_or(natural_height));
        let has_fixed_width = specified.is_some() || width < fill;
        let preferred_content = if has_fixed_width { width } else { extent };
        LayoutBox {
            node,
            rect: Rect {
                x: rect_x,
                y,
                width: width + frame,
                height: content_height + frame_height(&style),
            },
            style,
            children,
            fragments: Vec::new(),
            preferred_width: preferred_content + frame + margin.left + margin.right,
        }
    }

    /// Lays out the items of a row container, relative to its content box.
    /// Returns the item boxes, the content height and the preferred content width.
    #[allow(
        clippy::too_many_arguments,
        reason = "the pieces of one container's state"
    )]
    fn flex_rows(
        &self,
        node: NodeId,
        style: &Style,
        items: &[FlexItem],
        measures: &[FlexMeasure],
        width: f32,
        fixed_height: Option<f32>,
        measuring: bool,
    ) -> (Vec<LayoutBox>, f32, f32) {
        let (row_gap, column_gap) = style.gap;
        let outer = |measure: &FlexMeasure| measure.base + measure.outside;

        // Break the items into lines.
        let mut lines: Vec<std::ops::Range<usize>> = Vec::new();
        let (mut start, mut used) = (0, 0.0);
        for (index, measure) in measures.iter().enumerate() {
            let needed = outer(measure) + if index > start { column_gap } else { 0.0 };
            if style.flex_wrap
                && !measuring
                && index > start
                && used + needed > width + FIT_TOLERANCE
            {
                lines.push(start..index);
                (start, used) = (index, outer(measure));
            } else {
                used += needed;
            }
        }
        if start < measures.len() {
            lines.push(start..measures.len());
        }

        let mut boxes = Vec::with_capacity(items.len());
        let (mut cursor_y, mut extent) = (0.0f32, 0.0f32);
        let line_count = lines.len();
        for (line_index, line) in lines.into_iter().enumerate() {
            let count = line.len() as f32;
            let gaps = column_gap * (count - 1.0).max(0.0);
            let total: f32 = measures[line.clone()].iter().map(outer).sum::<f32>() + gaps;
            extent = extent.max(total);
            let mut free = if measuring { 0.0 } else { width - total };

            // Growing items take up free space, and when there is too little every item gives some up.
            let mut bases: Vec<f32> = measures[line.clone()].iter().map(|m| m.base).collect();
            let grow_total: f32 = measures[line.clone()].iter().map(|m| m.grow).sum();
            let base_total: f32 = bases.iter().sum();
            if free > 0.0 && grow_total > 0.0 {
                for (base, measure) in bases.iter_mut().zip(&measures[line.clone()]) {
                    *base += free * measure.grow / grow_total;
                }
                free = 0.0;
            } else if free < 0.0 && base_total > 0.0 {
                let keep = ((base_total + free) / base_total).max(0.0);
                bases.iter_mut().for_each(|base| *base *= keep);
                free = 0.0;
            }

            // Auto margins absorb what is left before `justify-content` gets a say.
            let auto_count = measures[line.clone()]
                .iter()
                .map(|m| {
                    usize::from(m.margin.left.is_none()) + usize::from(m.margin.right.is_none())
                })
                .sum::<usize>() as f32;
            let auto_margin = if auto_count > 0.0 {
                free.max(0.0) / auto_count
            } else {
                0.0
            };
            let spare = if auto_count > 0.0 { 0.0 } else { free.max(0.0) };
            let (lead, between) = match style.justify {
                Justify::Start => (0.0, 0.0),
                Justify::Center => (spare / 2.0, 0.0),
                Justify::End => (spare, 0.0),
                Justify::SpaceBetween if count > 1.0 => (0.0, spare / (count - 1.0)),
                Justify::SpaceBetween => (0.0, 0.0),
                Justify::SpaceAround => (spare / count / 2.0, spare / count),
                Justify::SpaceEvenly => (spare / (count + 1.0), spare / (count + 1.0)),
            };

            let mut line_boxes: Vec<LayoutBox> = line
                .clone()
                .zip(&bases)
                .map(|(index, &base)| self.flex_item(node, &items[index], Some(base), measuring))
                .collect();
            let vertical = |measure: &FlexMeasure| {
                (
                    measure.margin.top.unwrap_or(0.0),
                    measure.margin.bottom.unwrap_or(0.0),
                )
            };
            let tallest = line_boxes
                .iter()
                .zip(&measures[line.clone()])
                .map(|(item, measure)| item.rect.height + vertical(measure).0 + vertical(measure).1)
                .fold(0.0, f32::max);
            // A single line fills a container whose height is fixed.
            let line_height = match fixed_height {
                Some(height) if line_count == 1 => height.max(tallest),
                _ => tallest,
            };

            let mut cursor_x = lead;
            for (item, measure) in line_boxes.iter_mut().zip(&measures[line.clone()]) {
                let (top, bottom) = vertical(measure);
                let outer_height = item.rect.height + top + bottom;
                let offset = match style.align_items {
                    AlignItems::Stretch if measure.stretches => {
                        item.rect.height = line_height - top - bottom;
                        0.0
                    }
                    AlignItems::Stretch | AlignItems::Start => 0.0,
                    AlignItems::Center => (line_height - outer_height) / 2.0,
                    AlignItems::End => line_height - outer_height,
                };
                cursor_x += measure.margin.left.unwrap_or(auto_margin);
                item.translate(cursor_x, cursor_y + top + offset);
                cursor_x += item.rect.width
                    + measure.margin.right.unwrap_or(auto_margin)
                    + column_gap
                    + between;
            }
            boxes.append(&mut line_boxes);
            cursor_y += line_height
                + if line_index + 1 < line_count {
                    row_gap
                } else {
                    0.0
                };
        }
        (boxes, cursor_y, extent)
    }

    /// Lays out the items of a column container, relative to its content box.
    /// Returns the item boxes, the content height and the preferred content width.
    #[allow(
        clippy::too_many_arguments,
        reason = "the pieces of one container's state"
    )]
    fn flex_column(
        &self,
        node: NodeId,
        style: &Style,
        items: &[FlexItem],
        measures: &[FlexMeasure],
        width: f32,
        fixed_height: Option<f32>,
        measuring: bool,
    ) -> (Vec<LayoutBox>, f32, f32) {
        let row_gap = style.gap.0;
        let mut boxes = Vec::with_capacity(items.len());
        let (mut cursor_y, mut extent) = (0.0f32, 0.0f32);
        for (index, (item, measure)) in items.iter().zip(measures).enumerate() {
            extent = extent.max(measure.base + measure.outside);
            let room = (width - measure.outside).max(0.0);
            let has_width = matches!(item, FlexItem::Element(n) if self.style(*n).width.is_some());
            // Stretched items fill the container; the rest keep the width their content wants.
            let item_width = match style.align_items {
                AlignItems::Stretch if !has_width && !measuring => room,
                _ => measure
                    .base
                    .min(room.max(measure.base * f32::from(u8::from(measuring)))),
            };
            let mut laid_out = self.flex_item(node, item, Some(item_width), measuring);
            let free =
                (width - laid_out.rect.width - measure.outside + frame_of(self, item)).max(0.0);
            let left = match (measure.margin.left, measure.margin.right, style.align_items) {
                _ if measuring => measure.margin.left.unwrap_or(0.0),
                (None, None, _) => free / 2.0,
                (None, Some(_), _) => free,
                (Some(left), _, AlignItems::Center) => left + free / 2.0,
                (Some(left), _, AlignItems::End) => left + free,
                (Some(left), _, _) => left,
            };
            let (top, bottom) = (
                measure.margin.top.unwrap_or(0.0),
                measure.margin.bottom.unwrap_or(0.0),
            );
            laid_out.translate(left, cursor_y + top);
            cursor_y += laid_out.rect.height + top + bottom;
            if index + 1 < items.len() {
                cursor_y += row_gap;
            }
            boxes.push(laid_out);
        }

        // Spare height in a container of fixed height goes to growing items, then to `justify-content`.
        let spare = fixed_height.map_or(0.0, |height| (height - cursor_y).max(0.0));
        let grow_total: f32 = measures.iter().map(|m| m.grow).sum();
        if spare > 0.0 && !measuring {
            let count = boxes.len() as f32;
            let (lead, between) = match style.justify {
                _ if grow_total > 0.0 => (0.0, 0.0),
                Justify::Start => (0.0, 0.0),
                Justify::Center => (spare / 2.0, 0.0),
                Justify::End => (spare, 0.0),
                Justify::SpaceBetween if count > 1.0 => (0.0, spare / (count - 1.0)),
                Justify::SpaceBetween => (0.0, 0.0),
                Justify::SpaceAround => (spare / count / 2.0, spare / count),
                Justify::SpaceEvenly => (spare / (count + 1.0), spare / (count + 1.0)),
            };
            let mut shift = lead;
            for (item, measure) in boxes.iter_mut().zip(measures) {
                item.translate(0.0, shift);
                if grow_total > 0.0 {
                    let extra = spare * measure.grow / grow_total;
                    item.rect.height += extra;
                    shift += extra;
                }
                shift += between;
            }
        }
        (boxes, cursor_y, extent)
    }
}

/// The horizontal border and padding of a flex item, which is part of its box but not of its content.
fn frame_of(context: &Context<'_>, item: &FlexItem) -> f32 {
    match item {
        FlexItem::Element(node) => frame_width(context.style(*node)),
        FlexItem::Anonymous(_) => 0.0,
    }
}

/// Something waiting on the current line for the line to be finished.
struct LineItem {
    /// Offset from the start of the line.
    x: f32,
    width: f32,
    /// How far the item reaches above the baseline, including half of any extra line height.
    ascent: f32,
    /// How far it reaches below the baseline.
    descent: f32,
    kind: ItemKind,
}

enum ItemKind {
    Text {
        fragment: Fragment,
        font_ascent: f32,
    },
    Box {
        layout: Box<LayoutBox>,
        margin: Edges<f32>,
    },
}

/// The state of one block container while its children are being placed.
struct Flow<'c, 'a> {
    context: &'c Context<'a>,
    measuring: bool,
    /// The left edge and width of the content box.
    x: f32,
    width: f32,
    /// Where the next line or block goes.
    cursor: f32,
    /// The bottom margin of the previous block, which may collapse with the next top margin.
    pending_margin: f32,
    align: TextAlign,
    /// The container's own font, which gives every line a minimum ascent and descent.
    strut: (f32, f32),
    space_width: f32,
    line: Vec<LineItem>,
    line_width: f32,
    /// Whether collapsible whitespace was seen since the last item.
    pending_space: bool,
    children: Vec<LayoutBox>,
    fragments: Vec<Fragment>,
    /// The widest line or child seen, which is how wide the content wants to be.
    extent: f32,
}

impl<'c, 'a> Flow<'c, 'a> {
    fn new(
        context: &'c Context<'a>,
        node: NodeId,
        x: f32,
        width: f32,
        y: f32,
        measuring: bool,
    ) -> Self {
        let style = context.style(node);
        let (ascent, descent) = text_extent(context.fonts, style);
        Self {
            context,
            measuring,
            x,
            width,
            cursor: y,
            pending_margin: 0.0,
            align: style.text_align,
            strut: (ascent, descent),
            space_width: context.fonts.measure(" ", style.font_size, style.face()),
            line: Vec::new(),
            line_width: 0.0,
            pending_space: false,
            children: Vec::new(),
            fragments: Vec::new(),
            extent: 0.0,
        }
    }

    /// Makes room for `width` more on the line, breaking first if it does not fit.
    /// Returns the gap to leave before the new item.
    fn make_room(&mut self, width: f32, space: f32, may_break: bool) -> f32 {
        let mut gap = if self.pending_space && !self.line.is_empty() {
            space
        } else {
            0.0
        };
        if may_break
            && !self.line.is_empty()
            && self.line_width + gap + width > self.width + FIT_TOLERANCE
        {
            self.flush_line();
            gap = 0.0;
        }
        if self.line.is_empty() {
            // Inline content after a block starts below that block's bottom margin.
            self.cursor += self.pending_margin;
            self.pending_margin = 0.0;
        }
        self.pending_space = false;
        gap
    }

    fn text(&mut self, node: NodeId, text: &str, style: &Style) {
        let fonts = self.context.fonts;
        let (size, bold) = (style.font_size, style.face());
        let metrics = fonts.metrics(size, bold);
        let (ascent, descent) = text_extent(fonts, style);
        let space = fonts.measure(" ", size, bold);

        if text.starts_with(|c: char| c.is_ascii_whitespace()) {
            self.pending_space = true;
        }
        for (index, word) in text.split_ascii_whitespace().enumerate() {
            if index > 0 {
                self.pending_space = true;
            }
            let transformed = match style.text_transform {
                TextTransform::None => None,
                TextTransform::Uppercase => Some(word.to_uppercase()),
                TextTransform::Lowercase => Some(word.to_lowercase()),
                TextTransform::Capitalize => {
                    let mut letters = word.chars();
                    letters
                        .next()
                        .map(|first| first.to_uppercase().chain(letters).collect())
                }
            };
            let word = transformed.as_deref().unwrap_or(word);
            let width = fonts.measure(word, size, bold);
            let gap = self.make_room(width, space, !style.nowrap);
            let continues = matches!(
                self.line.last(),
                Some(LineItem { kind: ItemKind::Text { fragment, .. }, .. }) if fragment.node == node
            );
            if continues
                && let Some(LineItem {
                    width: item_width,
                    kind: ItemKind::Text { fragment, .. },
                    ..
                }) = self.line.last_mut()
            {
                // Consecutive words of one text node stay one run, which keeps painting cheap.
                if gap > 0.0 {
                    fragment.text.push(' ');
                }
                fragment.text.push_str(word);
                *item_width += gap + width;
            } else {
                self.line.push(LineItem {
                    x: self.line_width + gap,
                    width,
                    ascent,
                    descent,
                    kind: ItemKind::Text {
                        fragment: Fragment {
                            node,
                            rect: Rect {
                                x: 0.0,
                                y: 0.0,
                                width: 0.0,
                                height: metrics.ascent + metrics.descent,
                            },
                            baseline: 0.0,
                            text: word.to_owned(),
                            size,
                            face: bold,
                            color: style.text_color(),
                            underline: style.underline,
                        },
                        font_ascent: metrics.ascent,
                    },
                });
            }
            self.line_width += gap + width;
        }
        if text.ends_with(|c: char| c.is_ascii_whitespace()) {
            self.pending_space = true;
        }
    }

    /// Places a box that behaves like one large character.
    fn atomic(&mut self, layout: LayoutBox, margin: Edges<f32>, nowrap: bool) {
        let width = layout.rect.width + margin.left + margin.right;
        let gap = self.make_room(width, self.space_width, !nowrap);
        self.line.push(LineItem {
            x: self.line_width + gap,
            width,
            // The bottom margin edge sits on the baseline.
            ascent: layout.rect.height + margin.top + margin.bottom,
            descent: 0.0,
            kind: ItemKind::Box {
                layout: Box::new(layout),
                margin,
            },
        });
        self.line_width += gap + width;
    }

    /// A forced break. On an empty line it still takes up one line of the break's own height.
    fn line_break(&mut self, style: &Style) {
        if self.line.is_empty() {
            let (ascent, descent) = text_extent(self.context.fonts, style);
            self.cursor += self.pending_margin + ascent + descent;
            self.pending_margin = 0.0;
            self.pending_space = false;
        } else {
            self.flush_line();
        }
    }

    fn block_child(&mut self, node: NodeId) {
        self.flush_line();
        let margin = margins(self.context.style(node));
        let y = self.cursor + collapse(self.pending_margin, margin.top);
        let child = self
            .context
            .flow_box(node, self.width, self.x, y, self.measuring);
        self.cursor = child.rect.y + child.rect.height;
        self.pending_margin = margin.bottom;
        self.extent = self.extent.max(child.preferred_width);
        self.children.push(child);
    }

    /// Finishes the current line: aligns it, sets its height and positions everything on it.
    fn flush_line(&mut self) {
        self.pending_space = false;
        if self.line.is_empty() {
            return;
        }
        let ascent = self
            .line
            .iter()
            .map(|item| item.ascent)
            .fold(self.strut.0, f32::max);
        let descent = self
            .line
            .iter()
            .map(|item| item.descent)
            .fold(self.strut.1, f32::max);
        let free = (self.width - self.line_width).max(0.0);
        let offset = match self.align {
            _ if self.measuring => 0.0,
            TextAlign::Left => 0.0,
            TextAlign::Center => free / 2.0,
            TextAlign::Right => free,
        };
        let baseline = self.cursor + ascent;
        for item in self.line.drain(..) {
            let x = self.x + offset + item.x;
            match item.kind {
                ItemKind::Text {
                    mut fragment,
                    font_ascent,
                } => {
                    fragment.rect.x = x;
                    fragment.rect.y = baseline - font_ascent;
                    fragment.rect.width = item.width;
                    fragment.baseline = baseline;
                    self.fragments.push(fragment);
                }
                ItemKind::Box { mut layout, margin } => {
                    let top = baseline - item.ascent + margin.top;
                    layout.translate(x + margin.left - layout.rect.x, top - layout.rect.y);
                    self.children.push(*layout);
                }
            }
        }
        self.extent = self.extent.max(self.line_width);
        self.cursor += ascent + descent;
        self.line_width = 0.0;
    }

    /// Returns the child boxes, the text, the bottom of the content and the preferred width.
    fn finish(mut self) -> (Vec<LayoutBox>, Vec<Fragment>, f32, f32) {
        self.flush_line();
        // The last child's bottom margin stays inside this box.
        let bottom = self.cursor + self.pending_margin;
        (self.children, self.fragments, bottom, self.extent)
    }
}

/// How far text in this style reaches above and below the baseline, with the
/// line height's extra space split evenly between the two.
fn text_extent(fonts: &Fonts, style: &Style) -> (f32, f32) {
    let metrics = fonts.metrics(style.font_size, style.face());
    let content = metrics.ascent + metrics.descent;
    let half_leading = (style.used_line_height(content + metrics.line_gap) - content) / 2.0;
    (
        metrics.ascent + half_leading,
        metrics.descent + half_leading,
    )
}

